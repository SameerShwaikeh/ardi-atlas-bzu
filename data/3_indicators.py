"""Ardi indicators + backtest for ONE point.
Inputs (same folder; a missing file only skips the parts that need it):
  power_daily.csv            from 1_get_power.py
  imerg_daily.csv            from 2_get_imerg.py  (or the CSV downloaded from Giovanni)
  *MOD13Q1-061-results.csv   from AppEEARS
  *SRTMGL1-NC-003-results.csv from AppEEARS
Outputs: seasons_*.csv, backtest.csv, bare_months.csv, ardi_summary.md, and ardi_data.json
(ardi_data.json follows DATA_CONTRACT.md: it is the ONLY file the app reads).
MODIS NDVI = mean of the 3x3 m_* points when present (merged from Tia's version).
Every table is labelled with dataset, resolution and the date range FOUND IN THE FILE.
pip install pandas numpy
"""
import glob, json, math, re, sys, datetime as dt
import numpy as np, pandas as pd

# ---- thresholds (the plan's numbers; change here only) ----------------------
SEASON_MONTHS = [10, 11, 12, 1, 2, 3, 4, 5]   # Oct-May
DRY_DAY_MM, DRY_SPELL_DAYS, SPELL_MONTHS = 1.0, 10, [1, 2, 3]
HEAVY_MM = 20.0
HEAT_C, HEAT_MONTHS = 32.0, [3, 4, 5]
FROST_C = 0.0
BARE_NDVI = 0.2
PEAK_MONTHS = [12, 1, 2, 3, 4, 5]             # window searched for the season's NDVI peak
DRY_RANK = 5                                  # "the 5th-driest season"
MIN_COVER = 0.98                              # season needs >= 98 % of its days
POINT_ID, SPACING_M = "center", 90.0

out = []
temp = bare = bt = None
slope_info = {}
def say(s=""):
    print(s); out.append(s)
def table(df, floatfmt="{:.1f}"):
    d = df.copy()
    for c in d:
        if d[c].dtype.kind == "f":
            d[c] = d[c].map(lambda v: "" if pd.isna(v) else floatfmt.format(v))
    cols = [str(c) for c in d.columns]
    say("| " + " | ".join(cols) + " |"); say("|" + "---|" * len(cols))
    for _, r in d.iterrows():
        say("| " + " | ".join(str(v) for v in r.values) + " |")
    say()

def season_of(ts):
    """Season label by its starting year: Oct 2000-May 2001 -> '2000/01'."""
    y = ts.year if ts.month >= 10 else ts.year - 1
    return f"{y}/{str(y + 1)[2:]}"
def agyear_of(ts):                            # Oct-Sep year, same label style
    return season_of(ts)

def load_date_value(path):
    """Reads any 'date,value' text (our CSV or a Giovanni download with header lines)."""
    pat = re.compile(r"^\s*(\d{4}-\d{2}-\d{2})[T ]?[\d:]*Z?\s*,\s*(-?\d+(?:\.\d+)?(?:[eE][-+]?\d+)?)")
    rows = [(m.group(1), float(m.group(2))) for m in map(pat.match, open(path)) if m]
    s = pd.Series(dict(rows), dtype=float); s.index = pd.to_datetime(s.index)
    s[s < 0] = np.nan
    return s.sort_index()

def season_days(year0):
    return pd.date_range(f"{year0}-10-01", f"{year0 + 1}-05-31")

def rain_stats(rain, name):
    """Per-season rain indicators from a daily series (mm/day)."""
    rows = []
    for y0 in range(rain.index.min().year - 1, rain.index.max().year + 1):
        days = season_days(y0)
        s = rain.reindex(days)
        if s.notna().mean() < MIN_COVER:
            continue                          # incomplete season: not ranked
        jfm = s[s.index.month.isin(SPELL_MONTHS)]
        dry = (jfm < DRY_DAY_MM).astype(int)  # a missing day breaks a spell
        runs = dry.groupby((dry != dry.shift()).cumsum()).agg(["sum", "size"])
        runs = runs[runs["sum"] > 0]["size"]
        rows.append({"season": f"{y0}/{str(y0 + 1)[2:]}",
                     f"rain_mm": s.sum(),
                     f"dry_spells_10d_JFM": int((runs >= DRY_SPELL_DAYS).sum()),
                     f"longest_dry_run_JFM_days": int(runs.max()) if len(runs) else 0,
                     f"days_ge_20mm": int((s >= HEAVY_MM).sum())})
    df = pd.DataFrame(rows)
    if df.empty:
        return df
    df["rank_driest"] = df["rain_mm"].rank(method="min").astype(int)   # 1 = driest
    df["pct_of_mean"] = 100 * df["rain_mm"] / df["rain_mm"].mean()
    return df

def span(s):
    s = s.dropna()
    return f"{s.index.min().date()} to {s.index.max().date()}"

say("# Ardi indicators - one point")
say("Generated by 3_indicators.py from downloaded files. Nothing here is typed in by hand.")
say()

# ---------------- rain: IMERG ------------------------------------------------
imerg = seasons_i = None
try:
    imerg = load_date_value("imerg_daily.csv")
    seasons_i = rain_stats(imerg, "IMERG")
    LBL_I = f"IMERG V07 Final Daily (GPM_3IMERGDF.07), 0.1 deg grid cell (~11 km), file covers {span(imerg)}"
    say("## 1. Rain seasons (Oct-May) - IMERG"); say(f"Source: {LBL_I}. Complete seasons: {len(seasons_i)}."); say()
    table(seasons_i.sort_values("rank_driest"))
    if len(seasons_i) >= DRY_RANK:
        r = seasons_i.sort_values("rain_mm").iloc[DRY_RANK - 1]
        say(f"**Dry-year line (5th-driest of {len(seasons_i)} IMERG seasons): {r.season}, "
            f"{r.rain_mm:.0f} mm = {r.pct_of_mean:.0f} % of the {len(seasons_i)}-season mean "
            f"({seasons_i.rain_mm.mean():.0f} mm).** Roughly a 1-in-{len(seasons_i) / DRY_RANK:.0f} season."); say()
except FileNotFoundError:
    say("## 1. Rain seasons - IMERG: imerg_daily.csv NOT FOUND, skipped."); say()

# ---------------- POWER: rain (long record) + temperature --------------------
power = seasons_p = None
try:
    power = pd.read_csv("power_daily.csv", parse_dates=["date"], index_col="date")
    LBL_P = f"NASA POWER daily (MERRA-2), 0.5 x 0.625 deg grid cell (~55 x 59 km), file covers {span(power['T2M_MAX'])}"
    seasons_p = rain_stats(power["PRECTOTCORR"], "POWER")
    say("## 2. Rain seasons (Oct-May) - POWER PRECTOTCORR (longer record, coarser cell)")
    say(f"Source: {LBL_P}. Complete seasons: {len(seasons_p)}. Model-based rain averaged over a cell far "
        "bigger than the plain: use for the long view, not as the field's rain."); say()
    table(seasons_p.sort_values("rank_driest"))
    if len(seasons_p) >= DRY_RANK:
        r = seasons_p.sort_values("rain_mm").iloc[DRY_RANK - 1]
        say(f"5th-driest of {len(seasons_p)} POWER seasons: {r.season}, {r.rain_mm:.0f} mm "
            f"({r.pct_of_mean:.0f} % of mean). Roughly a 1-in-{len(seasons_p) / DRY_RANK:.0f} season."); say()

    rows = []
    for y0 in range(power.index.min().year - 1, power.index.max().year + 1):
        d = power.reindex(season_days(y0))
        if d["T2M_MAX"].notna().mean() < MIN_COVER:
            continue
        mam = d[d.index.month.isin(HEAT_MONTHS)]
        rows.append({"season": f"{y0}/{str(y0 + 1)[2:]}",
                     "heat_days_gt32_MarMay": int((mam["T2M_MAX"] > HEAT_C).sum()),
                     "frost_days_lt0_OctMay": int((d["T2M_MIN"] < FROST_C).sum()),
                     "min_T2M_MIN_C": d["T2M_MIN"].min(), "max_T2M_MAX_MarMay_C": mam["T2M_MAX"].max()})
    temp = pd.DataFrame(rows)
    say("## 3. Heat and frost - POWER T2M_MAX / T2M_MIN")
    say(f"Source: {LBL_P}. 2 m air temperature averaged over the grid cell at the cell's mean "
        "elevation (see power_meta.json), so frost on the plain floor is probably UNDER-counted."); say()
    table(temp)
    n = len(temp)
    say(f"Seasons with >=1 heat day (>32 C, Mar-May): {(temp.heat_days_gt32_MarMay > 0).sum()} of {n}. "
        f"Seasons with >=1 frost day (<0 C): {(temp.frost_days_lt0_OctMay > 0).sum()} of {n}."); say()
    if seasons_i is not None and len(seasons_i):
        both = seasons_i.merge(seasons_p, on="season", suffixes=("_imerg", "_power"))
        say(f"IMERG vs POWER season totals, {len(both)} shared seasons: Spearman rank correlation = "
            f"{both.rain_mm_imerg.corr(both.rain_mm_power, method='spearman'):.2f} (computed)."); say()
except FileNotFoundError:
    say("## 2-3. POWER: power_daily.csv NOT FOUND, skipped."); say()

# ---------------- MODIS NDVI -------------------------------------------------
ndvi = None
f = sorted(glob.glob("*MOD13Q1-061-results.csv"))
if f:
    m = pd.read_csv(f[0])
    c_ndvi = [c for c in m.columns if c.endswith("NDVI")][0]
    c_rel = [c for c in m.columns if c.endswith("pixel_reliability") and "Description" not in c]
    ids = m["ID"].astype(str)
    # AppEEARS strips "_" from IDs (m_0_0 -> m00); select the 3x3 block by Category instead
    is_grid = (m["Category"].astype(str) == "modis") if "Category" in m.columns else ids.str.startswith("m")
    use_grid = bool(is_grid.any())
    m = m[is_grid].copy() if use_grid else m[ids == POINT_ID].copy()
    m["Date"] = pd.to_datetime(m["Date"])
    v = pd.to_numeric(m[c_ndvi], errors="coerce")
    if v.abs().max() > 1.5:
        v = v * 0.0001                         # unscaled integers -> NDVI
    v[(v < -0.2) | (v > 1.0)] = np.nan         # fill values
    n_all = v.notna().sum()
    if c_rel:
        rel = pd.to_numeric(m[c_rel[0]], errors="coerce")
        v[~rel.isin([0, 1])] = np.nan          # keep good (0) + marginal (1); drop snow/cloud/fill
    ndvi = pd.Series(v.values, index=m["Date"]).groupby(level=0).mean().sort_index()   # mean of usable pixels per composite
    LBL_M = (f"MODIS Terra MOD13Q1 v061 NDVI, {'mean of a 3x3 block of ' if use_grid else ''}250 m pixels, "
             f"16-day composites, file covers {span(ndvi)}")
    say("## 4. Bare months per year - MODIS NDVI < 0.2")
    say(f"Source: {LBL_M}. {ndvi.notna().sum()} usable composites of {n_all} (pixel_reliability 0 or 1). "
        "Month value = mean of its usable composites. Year = Oct-Sep, labelled like the seasons."); say()
    mon = ndvi.dropna().resample("MS").mean()
    mon = mon.reindex(pd.date_range(mon.index.min(), mon.index.max(), freq="MS"))
    g = pd.DataFrame({"ndvi": mon, "year": [agyear_of(t) for t in mon.index]})
    bare = g.groupby("year").agg(bare_months=("ndvi", lambda x: int((x < BARE_NDVI).sum())),
                                 months_no_data=("ndvi", lambda x: int(x.isna().sum())),
                                 months_in_file=("ndvi", "size"), ndvi_min=("ndvi", "min")).reset_index()
    bare = bare[bare.months_in_file == 12].drop(columns="months_in_file")
    bare.to_csv("bare_months.csv", index=False)
    table(bare, "{:.2f}")
    say(f"Mean bare months per year: {bare.bare_months.mean():.1f} (range {bare.bare_months.min()}-{bare.bare_months.max()}, "
        f"{len(bare)} full years). Lowest monthly NDVI in the record: {mon.min():.2f}. If this is 0 every year, "
        "the 0.2 threshold is too low for this pixel: say so, do not tune it silently."); say()
else:
    say("## 4. MODIS: no *MOD13Q1-061-results.csv found, skipped."); say()

# ---------------- SRTM slope -------------------------------------------------
f = sorted(glob.glob("*SRTMGL1-NC-003-results.csv"))
if f:
    s = pd.read_csv(f[0]); c = [c for c in s.columns if c.endswith("DEM")][0]
    z = s.drop_duplicates("ID").set_index(s.drop_duplicates("ID")["ID"].astype(str))[c].astype(float)
    say("## 5. Elevation and slope - SRTM")
    try:
        dzdx = (z["E"] - z["W"]) / (2 * SPACING_M); dzdy = (z["N"] - z["S"]) / (2 * SPACING_M)
        pct = 100 * math.hypot(dzdx, dzdy)
        slope_info = {"slope_pct": round(pct, 1), "elevation_m": round(float(z[POINT_ID])), "note": "SRTM whole-metre heights; under ~1 % = flat"}
        say(f"Source: NASA SRTM v3 (SRTMGL1_NC.003), 1 arc-second (~30 m), acquired Feb 2000. "
            f"Elevation at point: {z[POINT_ID]:.0f} m. Neighbours 90 m away: N {z['N']:.0f}, S {z['S']:.0f}, "
            f"E {z['E']:.0f}, W {z['W']:.0f} m.")
        say(f"**Slope = {pct:.1f} % ({math.degrees(math.atan(pct / 100)):.1f} deg)** over a 180 m baseline. "
            f"SRTM heights are whole metres, so one step of 1 m = {100 / (2 * SPACING_M):.1f} % slope: "
            "treat anything under ~1 % as 'flat', not as a measured value."); say()
    except KeyError as e:
        say(f"Elevation at point: {z.get(POINT_ID, float('nan')):.0f} m. Slope NOT computed: neighbour {e} missing."); say()
else:
    say("## 5. SRTM: no *SRTMGL1-NC-003-results.csv found, skipped."); say()

# ---------------- BACKTEST ---------------------------------------------------
say("## 6. Backtest - did NDVI collapse in the driest IMERG seasons?")
if seasons_i is not None and ndvi is not None and len(seasons_i):
    pk = ndvi.dropna(); pk = pk[pk.index.month.isin(PEAK_MONTHS)]
    grp = pk.groupby([season_of(t) for t in pk.index])
    peak = pd.DataFrame({"season": list(grp.groups), "ndvi_peak": grp.max().values, "n_composites": grp.size().values})
    peak = peak[peak.n_composites >= 6]        # ~11 composites expected Dec-May; need >= 6
    first = ndvi.dropna().index.min()          # drop a season whose Dec-May window began before the NDVI record
    peak = peak[[pd.Timestamp(int(s[:4]), 12, 1) >= first for s in peak.season]]
    bt = seasons_i[["season", "rain_mm", "rank_driest"]].merge(peak, on="season")
    mu, sd = bt.ndvi_peak.mean(), bt.ndvi_peak.std()
    bt["anomaly"] = bt.ndvi_peak - mu
    bt["anomaly_sd"] = bt["anomaly"] / sd
    bt["ndvi_rank_lowest"] = bt.ndvi_peak.rank(method="min").astype(int)
    bt = bt.sort_values("rain_mm").reset_index(drop=True)
    bt.to_csv("backtest.csv", index=False)
    say(f"Rain: {LBL_I}."); say(f"NDVI: {LBL_M}. Peak = highest usable composite in Dec-May.")
    say(f"Shared seasons: {len(bt)} ({bt.season.min()} to {bt.season.max()}). Rain rank is among ALL IMERG seasons "
        f"(1 = driest); anomaly = peak minus the {len(bt)}-season mean peak ({mu:.2f}, SD {sd:.2f})."); say()
    show = bt.head(DRY_RANK).rename(columns={"season": "season", "rain_mm": "rain mm", "rank_driest": "rank",
                                             "ndvi_peak": "NDVI peak"})[["season", "rain mm", "rank", "NDVI peak", "anomaly", "anomaly_sd"]]
    show["rain mm"] = show["rain mm"].round(0).astype(int)
    show["NDVI peak"] = show["NDVI peak"].map("{:.2f}".format)
    table(show, "{:+.2f}")
    k = bt.head(DRY_RANK)
    rho = bt.rain_mm.corr(bt.ndvi_peak, method="spearman")
    say(f"- Driest {len(k)} seasons with NDVI peak below the mean: {(k.anomaly < 0).sum()} of {len(k)}.")
    say(f"- Driest {len(k)} seasons with NDVI peak more than 1 SD below the mean: {(k.anomaly_sd < -1).sum()} of {len(k)}.")
    say(f"- Of the {len(k)} lowest NDVI peaks, how many are among the driest {len(k)} seasons: "
        f"{(bt.nsmallest(len(k), 'ndvi_peak').season.isin(k.season)).sum()} of {len(k)}.")
    say(f"- Spearman rank correlation, season rain vs NDVI peak, all {len(bt)} seasons: {rho:.2f}.")
    say("Read it honestly: with ~25 seasons a correlation below ~0.4 is weak evidence. If NDVI did NOT fall in the "
        "dry seasons, likely reasons are irrigation in the pixel, a mixed 250 m pixel, or IMERG error. Report that, "
        "do not hide it."); say()
    say("Full table: backtest.csv")
else:
    say("Needs both imerg_daily.csv and the MOD13Q1 results file. Skipped.")
say()

if seasons_i is not None: seasons_i.to_csv("seasons_imerg.csv", index=False)
if seasons_p is not None: seasons_p.to_csv("seasons_power.csv", index=False)
open("ardi_summary.md", "w").write("\n".join(out))

# ---------------- ardi_data.json for the app (see DATA_CONTRACT.md) ----------
def num(x, nd=1):
    return None if x is None or (isinstance(x, float) and math.isnan(x)) else round(float(x), nd)
try:
    from config import LAT, LON, POINT_NAME
except Exception:
    LAT = LON = POINT_NAME = None
seasons = {}
if seasons_i is not None:
    for _, r in seasons_i.iterrows():
        seasons[r.season] = {"season": r.season, "rain_mm": num(r.rain_mm), "rank_driest": int(r.rank_driest),
                             "days_ge20mm": int(r.days_ge_20mm), "dry_spells_10d_jfm": int(r.dry_spells_10d_JFM),
                             "longest_dry_run_jfm": int(r.longest_dry_run_JFM_days)}
if temp is not None:
    for _, r in temp.iterrows():
        if r.season in seasons:
            seasons[r.season].update({"heat_days_mam": int(r.heat_days_gt32_MarMay), "frost_days": int(r.frost_days_lt0_OctMay)})
if bare is not None:
    for _, r in bare.iterrows():
        if r.year in seasons:
            seasons[r.year]["bare_months"] = int(r.bare_months)
if bt is not None:
    for _, r in bt.iterrows():
        if r.season in seasons:
            seasons[r.season]["ndvi_peak"] = num(r.ndvi_peak, 3)
dry = None
if seasons_i is not None and len(seasons_i) >= DRY_RANK:
    r = seasons_i.sort_values("rain_mm").iloc[DRY_RANK - 1]
    dry = {"season": r.season, "rain_mm": num(r.rain_mm), "rank": DRY_RANK, "n_seasons": int(len(seasons_i)),
           "pct_of_mean": num(r.pct_of_mean, 0), "mean_rain_mm": num(seasons_i.rain_mm.mean())}
backtest = None
if bt is not None and len(bt):
    k = bt.head(DRY_RANK)
    backtest = {"n_seasons": int(len(bt)), "driest_below_mean": int((k.anomaly < 0).sum()),
                "driest_below_1sd": int((k.anomaly_sd < -1).sum()), "spearman_rain_vs_ndvi": num(bt.rain_mm.corr(bt.ndvi_peak, method="spearman"), 2),
                "rows": [{"season": x.season, "rain_mm": num(x.rain_mm, 0), "rank": int(x.rank_driest), "ndvi_peak": num(x.ndvi_peak, 3),
                          "anomaly_sd": num(x.anomaly_sd, 2)} for _, x in k.iterrows()]}
datasets = []
if seasons_i is not None: datasets.append({"id": "imerg", "label": LBL_I, "role": "rain seasons, dry line, dry spells, heavy-rain days"})
if power is not None: datasets.append({"id": "power", "label": LBL_P, "role": "heat and frost days"})
if ndvi is not None: datasets.append({"id": "modis", "label": LBL_M, "role": "bare months, backtest"})
if slope_info: datasets.append({"id": "srtm", "label": "NASA SRTM v3 (SRTMGL1_NC.003), ~30 m, Feb 2000", "role": "slope"})
data = {"contract_version": 1, "placeholder": False,
        "generated": dt.datetime.now().isoformat(timespec="minutes"),
        "point": {"name": POINT_NAME, "lat": LAT, "lon": LON},
        "datasets": datasets,
        "seasons": [seasons[k] for k in sorted(seasons)],
        "dry_line": dry, "slope": slope_info or None, "backtest": backtest}
json.dump(data, open("ardi_data.json", "w"), indent=1, ensure_ascii=False)
print("wrote ardi_data.json (", len(data["seasons"]), "seasons ) - this is the file the app reads")
print("\nwrote ardi_summary.md (+ seasons_*.csv, backtest.csv, bare_months.csv)")
